"""界面里能安全显示的符号。

**中文界面字体里没有 ✓。** Microsoft YaHei、DengXian 这些都不含
U+2713 CHECK MARK，也不含 ✔ ✗ ✕ ✅ ❌ ⚠ ⛔ ⚙ ↔。写进界面字符串的话，
用户看到的是一个空心方框——不会崩、不会报错，只是每一处状态标记都变成
了豆腐块。实测流程条上"1 建模 ✓"显示成"1 建模 □"。

`QFontMetrics.inFont()` **判不了这件事**：它按主字体查，不考虑回退，
把"结""点""，"这些明明能正常显示的常用汉字也报成缺失。唯一可靠的判法是
把字符画出来，和一个私用区码位（任何字体都没有，必然是豆腐块）比像素——
tests/test_desktop_glyphs.py 就是这么做的。

所以符号一律从这里取，不要在界面字符串里直接写。这里的每一个都经过
渲染验证。
"""

from __future__ import annotations

#: 对勾。中文界面本来就用 √ 而不是 ✓，这里不是将就，是本来就该这样。
TICK = "√"
#: 叉。U+00D7 乘号，字体覆盖面比 ✗ ✕ ❌ 都广。
CROSS = "×"
#: 警告。空心三角比 ⚠ 安全，而且在浅色 chrome 上更克制。
WARN = "△"
#: 阻断级问题。实心圆，比空心三角更重。
BLOCK = "●"
#: 进行中 / 运行。
BUSY = "◆"
#: 中间点，用于分隔。
DOT = "·"

#: 汉堡菜单。☰ (U+2630) 画不出来，≡ 是同一个意思且字体里有。
MENU = "≡"
#: 折叠/展开。⌃ ⌄ (U+2303/2304) 画不出来。
CHEVRON_UP = "∧"
CHEVRON_DOWN = "∨"
#: 展开箭头（收起时朝右、展开时朝下）。▸ ▾ ▶ ► ▷ 一族全都画不出来。
DISCLOSE_CLOSED = "›"
DISCLOSE_OPEN = "∨"
#: 矩形工具。▭ 画不出来，□ 可以。
RECT = "□"
#: 撤销。↶ ↺ ⟲ ↻ ↩ ⎌ **全部**画不出来，只能退回文字。
#:
#: 这条留着当提醒：不是每个概念都找得到能显示的符号，找不到就写字，
#: 不要挑一个"看起来最像"的塞进去——那只会变成又一个豆腐块。
UNDO = ""

#: 全部符号，供闸门逐个渲染验证。新增一个就加进来。
ALL = (TICK, CROSS, WARN, BLOCK, BUSY, DOT, MENU, CHEVRON_UP,
       CHEVRON_DOWN, DISCLOSE_CLOSED, DISCLOSE_OPEN, RECT)
